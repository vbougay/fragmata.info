/**
 * Compiles data/snapshots/<id>/ folders into what the app imports:
 *   src/generated/snapshots/<id>.json   one DatasetSnapshot per dataset
 *   src/generated/snapshotIndex.ts      the dataset list (newest first), a static
 *                                       import of the newest, a lazy import() per older one
 * Validates every snapshot first and exits non-zero on any problem.
 *
 * Runs from `pnpm generate` (and so from postinstall, dev:next, og and build).
 * Output is gitignored. To add a dataset: add its folder, then run `pnpm generate`.
 * See docs/plans/data-snapshots-migration.md.
 */
import fs from 'node:fs';
import path from 'node:path';
import { listSnapshotIds, readSnapshot, validateSnapshot, SNAPSHOT_ROOT } from './snapshots-lib';

const MONTH_NAMES = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const MONTHS = ['JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN', 'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'];
const labelFor = (id: string) => `${MONTH_NAMES[MONTHS.indexOf(id.slice(3, 6))]} ${Number(id.slice(0, 2))}, ${id.slice(7)}`;

const outDir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../src/generated');
const snapDir = path.join(outDir, 'snapshots');

const ids = listSnapshotIds();
if (ids.length === 0) { console.error('build-snapshots: no folders in data/snapshots'); process.exit(1); }

const problems: string[] = [];
const snapshots = ids.map(id => {
  try {
    const s = readSnapshot(id);
    problems.push(...validateSnapshot(s));
    return s;
  } catch (e) {
    problems.push(`${id}: cannot read folder (${(e as Error).message.split('\n')[0]})`);
    return null;
  }
});
// A copied folder whose narrative files weren't rewritten would ship the previous
// day's text under the new date; validation can't see that any other way.
if (ids.length > 1) {
  const [a, b] = ids.map(id => path.join(SNAPSHOT_ROOT, id));
  for (const f of ['summary.en.md', 'summary.el.md', 'summary.ru.md', 'dams.json']) {
    const pa = path.join(a, f), pb = path.join(b, f);
    if (fs.existsSync(pa) && fs.existsSync(pb) && fs.readFileSync(pa).equals(fs.readFileSync(pb))) {
      problems.push(`${ids[0]}: ${f} is identical to ${ids[1]}'s (copied and not rewritten?)`);
    }
  }
}
if (problems.length) {
  console.error(`build-snapshots: ${problems.length} problem(s)\n  ${problems.join('\n  ')}`);
  process.exit(1);
}

// Write only what changed, and drop outputs for folders that no longer exist
fs.mkdirSync(snapDir, { recursive: true });
const writeIfChanged = (p: string, body: string) => {
  if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== body) { fs.writeFileSync(p, body); return 1; }
  return 0;
};
let changed = 0;
for (const s of snapshots) changed += writeIfChanged(path.join(snapDir, `${s!.id}.json`), JSON.stringify(s));
const keep = new Set(ids.map(id => `${id}.json`));
for (const f of fs.readdirSync(snapDir)) if (!keep.has(f)) { fs.rmSync(path.join(snapDir, f)); changed++; }

const [newest, ...older] = ids;
const index = `// GENERATED by scripts/build/build-snapshots.ts from data/snapshots/. Do not edit; gitignored.
import type { DatasetSnapshot } from '../utils/dataManager';
import newestSnapshot from './snapshots/${newest}.json';

/** Every dataset, newest first. */
export const availableDataSets = [
${ids.map(id => `  { id: '${id}', label: '${labelFor(id)}', value: '${id}' },`).join('\n')}
];

/** The newest dataset, bundled with the app. */
export const NEWEST_SNAPSHOT = newestSnapshot as unknown as DatasetSnapshot;

/** Older datasets, each its own lazy chunk. */
export const snapshotLoaders: Record<string, () => Promise<DatasetSnapshot>> = {
${older.map(id => `  '${id}': () => import('./snapshots/${id}.json').then(m => m.default as unknown as DatasetSnapshot),`).join('\n')}
};
`;
changed += writeIfChanged(path.join(outDir, 'snapshotIndex.ts'), index);
console.log(`build-snapshots: ${ids.length} datasets, newest ${newest}, ${changed} file(s) updated`);
