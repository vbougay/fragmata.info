/**
 * Writes src/generated/historyDigest.ts from src/utils/historicalStorageData.ts.
 *
 * The full bi-monthly table (1988 on, ~450 KB) used to sit in the first-load JS of
 * every dashboard, dam and region page, though those pages only need:
 *   - the earliest entry of each month (forecast water balance, October baseline)
 *   - the last ~12 months in full (sparklines)
 * The digest ships just that; the full table stays in the lazy heatmap and article
 * charts.
 *
 * Runs from `postinstall`, `dev:next`, `og` and `build`, so the output (gitignored)
 * is never stale where it matters. Run it by hand after editing
 * historicalStorageData.ts if a dev server is already running:
 *   npx tsx scripts/build/history-digest.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { historicalStorageData as rows } from '../../src/utils/historicalStorageData';

// Months of full history kept for the sparklines. They show 12 and apply their
// own cutoff; 14 leaves room for date and timezone edge cases.
const RECENT_MONTHS = 14;

const fail = (msg: string): never => {
  console.error(`history-digest: ${msg}`);
  process.exit(1);
};

if (rows.length === 0) fail('historicalStorageData is empty');
const keys = Object.keys(rows[0]).filter(k => k !== 'date');
for (const r of rows) {
  const k = Object.keys(r).filter(k => k !== 'date').sort();
  if (k.join() !== [...keys].sort().join()) fail(`entry ${r.date} has keys ${k.join()} (expected ${[...keys].sort().join()})`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date)) fail(`bad date ${r.date}`);
}
for (let i = 1; i < rows.length; i++) {
  if (rows[i].date <= rows[i - 1].date) fail(`not sorted: ${rows[i - 1].date} then ${rows[i].date}`);
}

// Earliest entry of each month. The forecast uses a month's earliest day-1..3 entry
// and the October baseline its earliest entry of any day; both read this list, which
// is only equivalent if a month's first entry is a day-1..3 one whenever it has one.
const monthly: typeof rows = [];
const byMonth = new Map<string, number[]>();
for (const r of rows) {
  const m = r.date.slice(0, 7);
  if (!byMonth.has(m)) { byMonth.set(m, []); monthly.push(r); }
  byMonth.get(m)!.push(Number(r.date.slice(8, 10)));
}
for (const [m, days] of byMonth) {
  if (days[0] > 3 && days.some(d => d <= 3)) fail(`${m}: first entry is day ${days[0]} but a day-1..3 entry exists`);
}

const last = rows[rows.length - 1].date;
let y = Number(last.slice(0, 4)), mo = Number(last.slice(5, 7)) - RECENT_MONTHS;
while (mo <= 0) { mo += 12; y--; }
const cutoff = `${y}-${String(mo).padStart(2, '0')}-01`;
const recent = rows.filter(r => r.date >= cutoff);

const toRow = (r: (typeof rows)[number]) =>
  JSON.stringify([r.date, ...keys.map(k => (r as unknown as Record<string, number | null>)[k])]);
const body = `// GENERATED by scripts/build/history-digest.ts from src/utils/historicalStorageData.ts.
// Do not edit; gitignored. ${rows.length} entries, ${rows[0].date} to ${last}.
export const DIGEST_KEYS = ${JSON.stringify(keys)} as const;
export type DigestRow = [string, ...(number | null)[]];
// Earliest entry of each month
export const monthlyRows: DigestRow[] = [
${monthly.map(toRow).join(',\n')}
];
// Every entry from ${cutoff} on
export const recentRows: DigestRow[] = [
${recent.map(toRow).join(',\n')}
];
`;

const out = path.join(path.dirname(new URL(import.meta.url).pathname), '../../src/generated/historyDigest.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
if (prev !== body) fs.writeFileSync(out, body);
console.log(`history-digest: ${monthly.length} months, ${recent.length} recent entries (from ${cutoff})${prev === body ? ', unchanged' : ''}`);
